/**
 * Отношение каталога, которое касается области: таблица списка, её секция или
 * наследник, любое отношение с колонкой области, представление над ними.
 */
export interface RelationFacts {
  oid: string;
  /** Имя так, как его печатает `regclass` (схема — если её нет в search_path). */
  display: string;
  kind: string;
  /** Имя из списка области, если отношение — таблица списка. */
  listed: string | null;
  /** Таблица списка, секцией или наследником которой отношение является. */
  root: string | null;
  /** Предок по наследованию таблицы списка или её секции, сам вне защиты. */
  ancestor: boolean;
  /** Владелец — сама роль сессии (`current_user` или `session_user`). */
  session_owned: boolean;
  rls: boolean;
  forced: boolean;
  /** Роль сессии (текущая или роль входа) — владелец или член роли-владельца. */
  owned: boolean;
  /** Тип колонки области (`regtype`: без модификатора длины, домен — своим именем). */
  column_type: string | null;
  /** Колация колонки области детерминирована (null — тип без колации). */
  deterministic: boolean | null;
  /** Значение `security_invoker` из параметров представления ('' — не задано). */
  invoker: string;
  /** Право TRUNCATE у роли, в которую сессия может войти. */
  truncate: boolean;
  /** Хоть одно право на данные (таблицы или колонки) у роли, в которую сессия может войти. */
  accessible: boolean;
}
