import type { Pool } from 'pg';

export interface ScopeReadyOptions {
  /**
   * Потолок всей проверки, мс (по умолчанию 30 000): ожидание соединения пула и
   * запросы. Не уложилась — отказ `undetermined`, а не зависший старт.
   */
  readonly timeoutMs?: number;
  /**
   * Пул, на котором строится эталон политик (временная таблица в откатываемой
   * транзакции). По умолчанию — проверяемый пул. Для реплики в восстановлении
   * (запись невозможна вовсе) — пул основного сервера той же базы.
   */
  readonly canonicalFrom?: Pool;
}
