/** Открытая работа области: по ней вложенный вызов узнаёт, в какой области он исполняется. */
export interface ScopeFrame {
  /** Пул, на соединении которого идёт транзакция. */
  readonly pool: unknown;
  readonly setting: string;
  /** Значение области; null — сквозной доступ. */
  readonly value: string | null;
  /** Ложь после конца транзакции: продолжения, запланированные из работы, рамкой больше не связаны. */
  active: boolean;
}
