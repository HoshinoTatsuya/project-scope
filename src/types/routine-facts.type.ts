/** Подпрограмма, созданная миграциями: что о ней известно гейту по тексту. */
export interface RoutineFacts {
  /** Исполняется правами владельца. */
  definer: boolean;
  /** Текст прямо называет таблицу области или представление над её данными. */
  touchesScope: boolean;
  /** Тело не прочесть: динамический SQL или язык, кроме sql и plpgsql. */
  opaque: boolean;
  /** Имена в тексте: по ним в конце истории ищутся вызовы других подпрограмм. */
  names: readonly string[];
  /** Миграция, где подпрограмма стала такой. */
  file: string;
  /** Прямое касание уже названо нарушением в этой миграции. */
  reported: boolean;
}
