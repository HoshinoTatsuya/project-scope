import { deepFreeze } from '../deep-freeze';

/**
 * Идентификатор и имя со схемой — источники регулярных выражений разбора
 * миграций. Идентификатор в кавычках бывает и юникодным (`U&"proj\0065ct_id"`):
 * сервер раскрывает его в `project_id`, и разбор обязан видеть то же имя.
 */
export const SQL_NAME_PATTERN = {
  identifier: `(?:[Uu]&"(?:[^"]|"")+"|"(?:[^"]|"")+"|[A-Za-z_][A-Za-z0-9_$]*)`,
  qualified: String.raw`(?:[Uu]&"(?:[^"]|"")+"|"(?:[^"]|"")+"|[A-Za-z_][A-Za-z0-9_$]*)(?: ?\. ?(?:[Uu]&"(?:[^"]|"")+"|"(?:[^"]|"")+"|[A-Za-z_][A-Za-z0-9_$]*))?`,
  /** Список имён со схемой через запятую (DROP TABLE a, b). */
  qualifiedList: String.raw`(?:[Uu]&"(?:[^"]|"")+"|"(?:[^"]|"")+"|[A-Za-z_][A-Za-z0-9_$]*)(?: ?\. ?(?:[Uu]&"(?:[^"]|"")+"|"(?:[^"]|"")+"|[A-Za-z_][A-Za-z0-9_$]*))?(?: ?, ?(?:[Uu]&"(?:[^"]|"")+"|"(?:[^"]|"")+"|[A-Za-z_][A-Za-z0-9_$]*)(?: ?\. ?(?:[Uu]&"(?:[^"]|"")+"|"(?:[^"]|"")+"|[A-Za-z_][A-Za-z0-9_$]*))?)*`,
} as const;

deepFreeze(SQL_NAME_PATTERN);
