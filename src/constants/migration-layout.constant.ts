import { deepFreeze } from '../deep-freeze';

/**
 * Раскладка каталога миграций — какой инструмент их применяет. От неё зависят
 * состав (что применится вообще) и порядок; угадывать её по именам файлов
 * нельзя: строковая сортировка ставит Flyway `V10__` раньше `V2__`, а файл
 * вне журнала drizzle не применяется вовсе.
 */
export const MIGRATION_LAYOUT = {
  /** drizzle-kit: `meta/_journal.json` (состав и порядок — из журнала) или каталоги `<время>_имя/migration.sql`. */
  drizzle: 'drizzle',
  /**
   * Flyway: всё дерево; `V<версия>__имя.sql` (суффикс в любом регистре) по
   * версии, `R__имя.sql` — после них по описанию; `U<версия>__` (откат) не
   * применяется; повтор версии — отказ.
   */
  flyway: 'flyway',
  /** golang-migrate: верхний уровень, `<номер>_имя.up.<любое расширение>` по номеру; `*.down.*` не применяется. */
  golangMigrate: 'golang-migrate',
  /** dbmate: верхний уровень, `<цифры>….sql` по имени файла строкой, только секция `-- migrate:up`. */
  dbmate: 'dbmate',
} as const;

deepFreeze(MIGRATION_LAYOUT);
