/**
 * Хвост `CREATE POLICY имя ON таблица …` для сравнения с эталоном: нижний
 * регистр, пробелы сведены к одному и сняты у скобок и запятых. Сравнивается
 * ТЕКСТ (с литералами и телами), а не маска: эталон, спрятанный в литерал или
 * тело `$x$…$x$`, полного совпадения не даёт.
 */
export function policyTail(text: string): string {
  return text
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .replace(/ ?([(),]) ?/g, '$1')
    .trim();
}
